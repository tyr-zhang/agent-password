package cli

import (
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"github.com/tyr-zhang/agent-password/internal/i18n"
)

// Contract sections are canonical English keys. Translating section by
// section (rather than one giant string) keeps drift localized.
const (
	contractIntro = `## AI integration contract

agent-pwd is a credential proxy: you can USE credentials but you cannot READ them.
Never try to print, dump, guess or exfiltrate a plaintext secret. There is no ` + "`cred show --secret`" + `, no HTTP API, no MCP server and no command that returns a stored value.`

	contractCan = `### What you can do
- Run SSH commands, SQL queries, API calls, and child processes with an injected environment variable.
- Request a one-time ` + "`fill`" + ` handle for a trusted child process; the handle is useless to a human reader.
- Ask for confirmation when a high-risk action is required.`

	contractCannot = `### What you cannot do
- ` + "`cred show`" + ` returns metadata only; reading vault.dat or audit.log never yields plaintext.
- Probing daemon memory or the IPC socket for keys is outside the CLI contract and will not help.
- You may not bypass, suppress, or auto-approve a confirmation request. If an action exits with code 10, STOP,
  surface the confirmation_id and poll token to a human, and do not retry until they approve it.`

	contractJSON = `### JSON output shape
The CLI prints the result object directly, e.g. {"status": "unlocked", ...}. Failures print
{"ok": false, "error": {"code": 20, "message": "..."}}. On the daemon IPC wire the envelope is
{"ok": true, "result": {...}}, but callers never see that envelope.
` + "`--human`" + ` switches to compact text; JSON is the default. Undeclared fields are never emitted.`

	contractExitCodes = `### Exit codes
0 success; 10 pending confirmation (a confirmation_id is returned); 20 vault locked or daemon not running;
30 policy denied; 40 credential not found; 1 other error (see error.code).`

	contractPending = `### Pending confirmation workflow
1. The action command exits 10 and prints confirmation_id + poll_token. Do not retry.
2. A human runs ` + "`agent-pwd confirm approve <id>`" + ` (Touch ID / Windows Hello, or master-password fallback).
3. Run ` + "`agent-pwd confirm result <id> --token <poll_token>`" + ` once to collect the final outcome.
   Use --wait on the original action if you want the command to block until the human decides.
Pending actions live only in daemon memory: a daemon restart cancels them.`

	contractSafety = `### Safety notes
- You may cause side effects through the commands you are allowed to execute (e.g. SQL writes or HTTP POSTs);
  the policy layer requires confirmation but cannot judge intent. Never treat these tools as permission to
  perform unrelated destructive actions.
- All actions are appended to a hash-chained audit log. Credentials can be removed or rotated immediately.`
)

var contractSections = []string{
	contractIntro, contractCan, contractCannot, contractJSON,
	contractExitCodes, contractPending, contractSafety,
}

var exitCodeMeanings = []string{
	"success",
	"pending human confirmation; confirmation_id returned",
	"vault locked or daemon not running",
	"policy denied",
	"credential not found",
	"other error",
}

func contractText(lang i18n.Lang) string {
	parts := make([]string, 0, len(contractSections))
	for _, key := range contractSections {
		parts = append(parts, i18n.T(lang, key))
	}
	return strings.Join(parts, "\n\n") + "\n"
}

func exitCodes(lang i18n.Lang) []map[string]any {
	codes := []int{0, 10, 20, 30, 40, 1}
	out := make([]map[string]any, 0, len(codes))
	for i, code := range codes {
		out = append(out, map[string]any{"code": code, "meaning": i18n.T(lang, exitCodeMeanings[i])})
	}
	return out
}

func init() {
	register(&Command{
		Name: "docs", Group: "Management (human)", Syntax: "agent-pwd docs [--format md|json]",
		Summary: "print the AI integration contract generated from this command registry",
		Flags:   []Flag{{Name: "format", Summary: "md or json", Default: "md"}},
		Doc:     []string{"Embed this output in CLAUDE.md or an agent skill description."},
		Run:     cmdDocs,
	})
}

func cmdDocs(c *Context) int {
	if c.String("format", "md") == "json" {
		b, err := json.MarshalIndent(docsJSON(c.Lang), "", "  ")
		if err != nil {
			return c.Fail(1, err.Error())
		}
		c.Print(string(b))
		return 0
	}
	c.Print(c.T("# agent-pwd — AI integration contract\n"))
	c.Print(c.T("Generated by `agent-pwd docs`; do not edit by hand.\n"))
	c.Print(c.T("All action commands emit JSON by default. Secrets never appear in output.\n"))
	c.Print(c.T("\n## Commands\n"))
	var names []string
	byName := map[string]*Command{}
	for _, cmd := range registry {
		if cmd.Hidden {
			continue
		}
		names = append(names, cmd.Name)
		byName[cmd.Name] = cmd
	}
	sort.Strings(names)
	groups := map[string][]string{}
	for _, n := range names {
		groups[byName[n].Group] = append(groups[byName[n].Group], n)
	}
	var groupNames []string
	for g := range groups {
		groupNames = append(groupNames, g)
	}
	sort.Strings(groupNames)
	for _, g := range groupNames {
		fmt.Fprintf(c.Stdout, "\n### %s\n\n", c.T(g))
		for _, n := range groups[g] {
			cmd := byName[n]
			fmt.Fprintf(c.Stdout, "- `%s` — %s\n", cmd.Syntax, c.T(cmd.Summary))
			if len(cmd.Flags) > 0 {
				var flags []string
				for _, f := range cmd.Flags {
					flags = append(flags, "--"+f.Name)
				}
				fmt.Fprintf(c.Stdout, "  flags: %s\n", strings.Join(flags, " "))
			}
		}
	}
	c.Print(contractText(c.Lang))
	return 0
}

func docsJSON(lang i18n.Lang) map[string]any {
	type commandDoc struct {
		Name    string   `json:"name"`
		Syntax  string   `json:"syntax"`
		Summary string   `json:"summary"`
		Flags   []string `json:"flags,omitempty"`
	}
	var cmds []commandDoc
	for _, cmd := range registry {
		if cmd.Hidden {
			continue
		}
		f := &commandDoc{Name: cmd.Name, Syntax: cmd.Syntax, Summary: i18n.T(lang, cmd.Summary)}
		for _, flag := range cmd.Flags {
			f.Flags = append(f.Flags, "--"+flag.Name)
		}
		cmds = append(cmds, *f)
	}
	return map[string]any{
		"version": 1, "commands": cmds, "exit_codes": exitCodes(lang), "contract": contractText(lang),
	}
}
